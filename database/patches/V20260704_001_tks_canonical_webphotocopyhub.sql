CREATE OR REPLACE FUNCTION fn_tks_set_tracking_columns()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.deleted := COALESCE(NEW.deleted, 0);

    IF TG_OP = 'INSERT' THEN
        NEW.created := COALESCE(NEW.created, CURRENT_TIMESTAMP);
        NEW.created_by := COALESCE(NEW.created_by, CURRENT_USER);
        NEW.created_by_function := COALESCE(NEW.created_by_function, TG_NAME);
    ELSE
        NEW.created := OLD.created;
        NEW.created_by := OLD.created_by;
        NEW.created_by_function := OLD.created_by_function;
    END IF;

    NEW.last_updated := CURRENT_TIMESTAMP;
    NEW.last_updated_by := COALESCE(NEW.last_updated_by, CURRENT_USER);
    NEW.last_updated_by_function := COALESCE(NEW.last_updated_by_function, TG_NAME);

    RETURN NEW;
END;
$$;

