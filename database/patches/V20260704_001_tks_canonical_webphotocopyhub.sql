CREATE OR REPLACE FUNCTION f2002_sp_sel_reconcile_vi_chi_nhanh()
RETURNS TABLE
(
    vi_chi_nhanh_id bigint,
    chi_nhanh_id bigint,
    thanh_vien_id bigint,
    so_du_hien_tai numeric(18,2),
    so_du_theo_giao_dich numeric(18,2),
    chenh_lech numeric(18,2)
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        a.auto_id AS vi_chi_nhanh_id,
        a.chi_nhanh_id,
        a.thanh_vien_id,
        a.so_du AS so_du_hien_tai,
        COALESCE(SUM(b.so_tien), 0)::numeric(18,2) AS so_du_theo_giao_dich,
        (a.so_du - COALESCE(SUM(b.so_tien), 0))::numeric(18,2) AS chenh_lech
    FROM tbl_tc_vi_chi_nhanh a
    LEFT JOIN tbl_tc_giao_dich_vi b
        ON b.vi_chi_nhanh_id = a.auto_id
        AND b.deleted = 0
    WHERE a.deleted = 0
    GROUP BY
        a.auto_id,
        a.chi_nhanh_id,
        a.thanh_vien_id,
        a.so_du;
$$;

