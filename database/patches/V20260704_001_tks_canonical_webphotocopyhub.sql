CREATE OR REPLACE FUNCTION f2004_sp_sel_reconcile_ton_kho_san_pham()
RETURNS TABLE
(
    ton_kho_san_pham_id bigint,
    chi_nhanh_id bigint,
    san_pham_id bigint,
    so_luong_ton integer,
    so_luong_theo_nhap_xuat integer,
    chenh_lech integer
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        a.auto_id AS ton_kho_san_pham_id,
        a.chi_nhanh_id,
        a.san_pham_id,
        a.so_luong_ton,
        COALESCE(SUM(b.so_luong_thay_doi), 0)::integer AS so_luong_theo_nhap_xuat,
        (a.so_luong_ton - COALESCE(SUM(b.so_luong_thay_doi), 0))::integer AS chenh_lech
    FROM tbl_xnk_ton_kho_san_pham a
    LEFT JOIN tbl_xnk_nhap_xuat_san_pham b
        ON b.ton_kho_san_pham_id = a.auto_id
        AND b.deleted = 0
    WHERE a.deleted = 0
    GROUP BY
        a.auto_id,
        a.chi_nhanh_id,
        a.san_pham_id,
        a.so_luong_ton;
$$;

CREATE OR REPLACE FUNCTION fq_sys_sp_sel_duplicate_idempotency_key()
RETURNS TABLE
(
    ten_bang varchar,
    idempotency_key varchar,
    chi_nhanh_id bigint,
    thanh_vien_id bigint,
    so_luong bigint
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        'tbl_tc_giao_dich_vi'::varchar AS ten_bang,
        lower(a.idempotency_key)::varchar AS idempotency_key,
        a.chi_nhanh_id,
        a.thanh_vien_id,
        count(*) AS so_luong
    FROM tbl_tc_giao_dich_vi a
    WHERE a.deleted = 0
        AND a.idempotency_key IS NOT NULL
    GROUP BY
        lower(a.idempotency_key),
        a.chi_nhanh_id,
        a.thanh_vien_id
    HAVING count(*) > 1
    UNION ALL
    SELECT
        'tbl_tc_yeu_cau_nap_tien'::varchar,
        lower(a.create_idempotency_key)::varchar,
        a.chi_nhanh_id,
        a.thanh_vien_id,
        count(*)
    FROM tbl_tc_yeu_cau_nap_tien a
    WHERE a.deleted = 0
        AND a.create_idempotency_key IS NOT NULL
    GROUP BY
        lower(a.create_idempotency_key),
        a.chi_nhanh_id,
        a.thanh_vien_id
    HAVING count(*) > 1
    UNION ALL
    SELECT
        'tbl_tc_don_in'::varchar,
        lower(a.submit_idempotency_key)::varchar,
        a.chi_nhanh_id,
        a.thanh_vien_id,
        count(*)
    FROM tbl_tc_don_in a
    WHERE a.deleted = 0
        AND a.submit_idempotency_key IS NOT NULL
    GROUP BY
        lower(a.submit_idempotency_key),
        a.chi_nhanh_id,
        a.thanh_vien_id
    HAVING count(*) > 1
    UNION ALL
    SELECT
        'tbl_tc_don_hang_san_pham'::varchar,
        lower(a.order_idempotency_key)::varchar,
        a.chi_nhanh_id,
        a.thanh_vien_id,
        count(*)
    FROM tbl_tc_don_hang_san_pham a
    WHERE a.deleted = 0
        AND a.order_idempotency_key IS NOT NULL
    GROUP BY
        lower(a.order_idempotency_key),
        a.chi_nhanh_id,
        a.thanh_vien_id
    HAVING count(*) > 1
    UNION ALL
    SELECT
        'tbl_tc_don_dich_vu_ho_tro'::varchar,
        lower(a.order_idempotency_key)::varchar,
        a.chi_nhanh_id,
        a.thanh_vien_id,
        count(*)
    FROM tbl_tc_don_dich_vu_ho_tro a
    WHERE a.deleted = 0
        AND a.order_idempotency_key IS NOT NULL
    GROUP BY
        lower(a.order_idempotency_key),
        a.chi_nhanh_id,
        a.thanh_vien_id
    HAVING count(*) > 1;
$$;

CREATE OR REPLACE FUNCTION fq_sys_sp_sel_cross_branch_violation()
RETURNS TABLE
(
    ma_loi varchar,
    ten_bang varchar,
    ref_id bigint,
    chi_nhanh_id bigint,
    chi_nhanh_lien_quan_id bigint,
    mo_ta varchar
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        'DON_IN_FILE'::varchar AS ma_loi,
        'tbl_tc_don_in'::varchar AS ten_bang,
        a.auto_id AS ref_id,
        a.chi_nhanh_id,
        b.chi_nhanh_id AS chi_nhanh_lien_quan_id,
        'Don in va file upload khac chi nhanh.'::varchar AS mo_ta
    FROM tbl_tc_don_in a
    JOIN tbl_tc_file_upload b
        ON b.auto_id = a.file_upload_id
        AND b.deleted = 0
    WHERE a.deleted = 0
        AND a.chi_nhanh_id <> b.chi_nhanh_id
    UNION ALL
    SELECT
        'DON_HANG_SAN_PHAM'::varchar,
        'tbl_tc_don_hang_san_pham_chi_tiet'::varchar,
        a.auto_id,
        b.chi_nhanh_id,
        c.chi_nhanh_id,
        'Don hang san pham va san pham khac chi nhanh.'::varchar
    FROM tbl_tc_don_hang_san_pham_chi_tiet a
    JOIN tbl_tc_don_hang_san_pham b
        ON b.auto_id = a.don_hang_san_pham_id
        AND b.deleted = 0
    JOIN tbl_dm_san_pham c
        ON c.auto_id = a.san_pham_id
        AND c.deleted = 0
    WHERE a.deleted = 0
        AND b.chi_nhanh_id <> c.chi_nhanh_id
    UNION ALL
    SELECT
        'DON_DICH_VU_HO_TRO'::varchar,
        'tbl_tc_don_dich_vu_ho_tro'::varchar,
        a.auto_id,
        a.chi_nhanh_id,
        b.chi_nhanh_id,
        'Don dich vu va dich vu ho tro khac chi nhanh.'::varchar
    FROM tbl_tc_don_dich_vu_ho_tro a
    JOIN tbl_dm_dich_vu_ho_tro b
        ON b.auto_id = a.dich_vu_ho_tro_id
        AND b.deleted = 0
    WHERE a.deleted = 0
        AND a.chi_nhanh_id <> b.chi_nhanh_id
    UNION ALL
    SELECT
        'VI_GIAO_DICH'::varchar,
        'tbl_tc_giao_dich_vi'::varchar,
        a.auto_id,
        a.chi_nhanh_id,
        b.chi_nhanh_id,
        'Giao dich vi va vi chi nhanh khac chi nhanh.'::varchar
    FROM tbl_tc_giao_dich_vi a
    JOIN tbl_tc_vi_chi_nhanh b
        ON b.auto_id = a.vi_chi_nhanh_id
        AND b.deleted = 0
    WHERE a.deleted = 0
        AND a.chi_nhanh_id <> b.chi_nhanh_id;
$$;

