CREATE OR REPLACE FUNCTION f2002_sp_ins_giao_dich_vi(
    p_i_chi_nhanh_id bigint,
    p_i_thanh_vien_id bigint,
    p_i_loai_giao_dich_id integer,
    p_dec_so_tien numeric,
    p_str_ref_type varchar,
    p_i_ref_id bigint,
    p_str_ghi_chu varchar,
    p_str_idempotency_key varchar,
    p_i_thuc_hien_boi_thanh_vien_id bigint,
    p_str_last_updated_by varchar,
    p_str_last_updated_by_function varchar
)
RETURNS bigint
LANGUAGE plpgsql
AS $$
DECLARE
    v_i_vi_chi_nhanh_id bigint;
    v_dec_so_du_truoc numeric(18,2);
    v_dec_so_du_sau numeric(18,2);
    v_i_existing_auto_id bigint;
    v_i_auto_id bigint;
BEGIN
    IF p_str_idempotency_key IS NOT NULL THEN
        SELECT a.auto_id
        INTO v_i_existing_auto_id
        FROM tbl_tc_giao_dich_vi a
        WHERE a.deleted = 0
            AND a.chi_nhanh_id = p_i_chi_nhanh_id
            AND a.thanh_vien_id = p_i_thanh_vien_id
            AND a.loai_giao_dich_id = p_i_loai_giao_dich_id
            AND lower(a.idempotency_key) = lower(p_str_idempotency_key)
        LIMIT 1;

        IF v_i_existing_auto_id IS NOT NULL THEN
            RETURN v_i_existing_auto_id;
        END IF;
    END IF;

    SELECT a.auto_id,
        a.so_du
    INTO v_i_vi_chi_nhanh_id,
        v_dec_so_du_truoc
    FROM tbl_tc_vi_chi_nhanh a
    WHERE a.deleted = 0
        AND a.chi_nhanh_id = p_i_chi_nhanh_id
        AND a.thanh_vien_id = p_i_thanh_vien_id
    FOR UPDATE;

    IF v_i_vi_chi_nhanh_id IS NULL THEN
        INSERT INTO tbl_tc_vi_chi_nhanh
        (
            chi_nhanh_id,
            thanh_vien_id,
            so_du,
            created_by,
            last_updated_by,
            created_by_function,
            last_updated_by_function
        )
        VALUES
        (
            p_i_chi_nhanh_id,
            p_i_thanh_vien_id,
            0,
            p_str_last_updated_by,
            p_str_last_updated_by,
            p_str_last_updated_by_function,
            p_str_last_updated_by_function
        )
        RETURNING auto_id,
            so_du
        INTO v_i_vi_chi_nhanh_id,
            v_dec_so_du_truoc;
    END IF;

    v_dec_so_du_sau := v_dec_so_du_truoc + p_dec_so_tien;

    IF v_dec_so_du_sau < 0 THEN
        RAISE EXCEPTION 'So du vi khong du.';
    END IF;

    UPDATE tbl_tc_vi_chi_nhanh
    SET so_du = v_dec_so_du_sau,
        version_no = version_no + 1,
        last_updated_by = p_str_last_updated_by,
        last_updated_by_function = p_str_last_updated_by_function
    WHERE auto_id = v_i_vi_chi_nhanh_id;

    INSERT INTO tbl_tc_giao_dich_vi
    (
        chi_nhanh_id,
        vi_chi_nhanh_id,
        thanh_vien_id,
        thuc_hien_boi_thanh_vien_id,
        loai_giao_dich_id,
        so_tien,
        so_du_truoc,
        so_du_sau,
        ref_type,
        ref_id,
        ghi_chu,
        idempotency_key,
        created_by,
        last_updated_by,
        created_by_function,
        last_updated_by_function
    )
    VALUES
    (
        p_i_chi_nhanh_id,
        v_i_vi_chi_nhanh_id,
        p_i_thanh_vien_id,
        p_i_thuc_hien_boi_thanh_vien_id,
        p_i_loai_giao_dich_id,
        p_dec_so_tien,
        v_dec_so_du_truoc,
        v_dec_so_du_sau,
        p_str_ref_type,
        p_i_ref_id,
        p_str_ghi_chu,
        p_str_idempotency_key,
        p_str_last_updated_by,
        p_str_last_updated_by,
        p_str_last_updated_by_function,
        p_str_last_updated_by_function
    )
    RETURNING auto_id INTO v_i_auto_id;

    RETURN v_i_auto_id;
END;
$$;

